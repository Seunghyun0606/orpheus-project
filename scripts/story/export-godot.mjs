// Story data for the Godot runtime (DEC-072, TASK-038).
//
//   node scripts/story/export-godot.mjs            write episodes and cast JSON and locale .po files
//   node scripts/story/export-godot.mjs --check    fail when the committed export is stale
//   node scripts/story/export-godot.mjs --fixtures also write parity fixtures (not committed)
//
// Episodes are exported after schema parsing, so defaults are filled in and the
// Godot runner never re-implements validation. Translations become gettext .po
// files keyed by the English text, the same keys the content catalogs use.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';

import { parseCast } from '../../src/story/cast.ts';
import { parseEpisode } from '../../src/story/schema.ts';
import { campaignCarries, enumeratePaths, flagsRead } from '../../src/story/validate.ts';
import {
  representativePaths,
  threeWayCarries,
  thresholdRuns,
  tripleKeys,
} from './parity-coverage.mjs';

const DATA = 'src/story/data/';
const CAST = 'src/story/cast.yaml';
const OUT = 'godot/data/episodes/';
const LOCALE = 'godot/locale/';
const FIXTURES = 'godot/tests/fixtures/';
const LOCALES = ['ko'];

const json = (value) => JSON.stringify(value, null, 2) + '\n';
const episodes = readdirSync(DATA)
  .filter((f) => f.endsWith('.yaml'))
  .sort()
  .map((f) => parseEpisode(readFileSync(DATA + f, 'utf8')));

const poString = (text) =>
  '"' + text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';

function poFile(locale) {
  const dir = `src/i18n/content/${locale}/`;
  const seen = new Map();
  for (const f of readdirSync(dir).sort()) {
    if (!f.startsWith('story-')) continue;
    for (const { en, [locale]: text } of parse(readFileSync(dir + f, 'utf8')).entries)
      if (typeof text === 'string' && text.length > 0) seen.set(en, text);
  }
  const header = [
    '# Generated by scripts/story/export-godot.mjs from src/i18n/content/' +
      locale +
      '/story-*.yaml.',
    '# Do not edit; translate the catalogs instead.',
    'msgid ""',
    'msgstr ""',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    `"Language: ${locale}\\n"`,
    '',
  ];
  const body = [...seen].flatMap(([en, text]) => [
    `msgid ${poString(en)}`,
    `msgstr ${poString(text)}`,
    '',
  ]);
  return [...header, ...body].join('\n');
}

const outputs = new Map();
for (const episode of episodes)
  outputs.set(`${OUT}${episode.id.toLowerCase()}.json`, json(episode));
outputs.set(`${OUT}index.json`, json(episodes.map(({ id, act, title }) => ({ id, act, title }))));
if (existsSync(CAST))
  outputs.set('godot/data/cast.json', json(parseCast(readFileSync(CAST, 'utf8'))));
for (const locale of LOCALES) outputs.set(`${LOCALE}${locale}.po`, poFile(locale));

if (process.argv.includes('--check')) {
  const stale = [...outputs].filter(
    ([file, content]) => !existsSync(file) || readFileSync(file, 'utf8') !== content,
  );
  for (const [file] of stale) console.error(`${file} is stale; run npm run godot:export`);
  if (stale.length > 0) process.exitCode = 1;
  else console.log('Godot story data is up to date.');
} else {
  for (const dir of [OUT, LOCALE]) mkdirSync(dir, { recursive: true });
  for (const [file, content] of outputs) writeFileSync(file, content);
  if (process.argv.includes('--fixtures')) {
    mkdirSync(FIXTURES, { recursive: true });
    const carries = campaignCarries(episodes);
    const coverage = [];
    for (const episode of episodes) {
      // Keep the existing bounded campaign sample; targeted synthetic carries
      // below exercise numeric boundaries and higher-order flag combinations.
      const runs = carries
        .get(episode.id)
        .slice(0, 12)
        .map((carry) => ({ carry, paths: enumeratePaths(episode, carry).paths }));
      const baselinePaths = runs.reduce((total, run) => total + run.paths.length, 0);
      const dialogue = (sample) =>
        sample.flatMap((run) =>
          run.paths.flatMap((path) =>
            path.state.feed.filter((entry) => ['line', 'log', 'narrate'].includes(entry.kind)),
          ),
        );
      const baselineDialogue = new Set(dialogue(runs).map((entry) => JSON.stringify(entry)));
      const thresholds = thresholdRuns(episode, runs);
      const flags = [...flagsRead(episode)].sort();
      const previouslyCovered = new Set(runs.flatMap((run) => tripleKeys(flags, run.carry)));
      const combinations = threeWayCarries(episode);
      const triples = new Set(combinations.flatMap((carry) => tripleKeys(flags, carry)));
      const flagRuns = combinations.map((carry) => ({
        carry,
        paths: representativePaths(episode, carry),
      }));
      const newDialogue = [
        ...new Map(
          dialogue([...thresholds.runs, ...flagRuns])
            .filter((entry) => !baselineDialogue.has(JSON.stringify(entry)))
            .map((entry) => [JSON.stringify(entry), entry]),
        ).values(),
      ];
      coverage.push({
        episode: episode.id,
        baselinePaths,
        thresholdPaths: thresholds.runs.length,
        thresholds: thresholds.coverage,
        flagPaths: flagRuns.reduce((total, run) => total + run.paths.length, 0),
        flagCarries: flagRuns.length,
        flagTripleCombinations: triples.size,
        newFlagTripleCombinations: [...triples].filter((key) => !previouslyCovered.has(key)).length,
        newDialogue,
      });
      runs.push(...thresholds.runs, ...flagRuns);
      writeFileSync(
        `${FIXTURES}${episode.id.toLowerCase()}.paths.json`,
        JSON.stringify({ episode: episode.id, runs }),
      );
    }
    writeFileSync(`${FIXTURES}coverage.json`, json(coverage));
    const total = (key) => coverage.reduce((sum, entry) => sum + entry[key], 0);
    console.log(
      `Parity fixtures: ${total('baselinePaths')} baseline + ${total('thresholdPaths')} boundary + ${total('flagPaths')} three-way flag paths.`,
    );
    console.log(`Coverage details: ${FIXTURES}coverage.json`);
  }
  console.log(`Exported ${episodes.length} episode(s) and ${LOCALES.length} locale(s).`);
}
